package com.spectrace.specification.bootstrap;

import com.spectrace.platform.starter.correlation.CorrelationId;
import com.spectrace.platform.starter.messaging.Outbox;
import com.spectrace.specification.application.SpecificationPublished;
import com.spectrace.specification.application.SpecificationService;
import com.spectrace.specification.persistence.SpecificationStore;
import com.spectrace.specification.persistence.SpecificationStore.MaterialRow;
import com.spectrace.specification.persistence.SpecificationStore.SpecificationRow;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.time.LocalDate;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;
import org.springframework.transaction.support.TransactionTemplate;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * Owner import of the synthetic G3 load dataset (G3-M1.1, STCN-89).
 *
 * <p>Reads {@code specification-owner-import.jsonl} (one SpecificationPublished.v1 envelope per line, as
 * generated by {@code perf/g3/experiment.py}) and stores each released version in this service's own
 * database with the dataset's IDs, version numbers and release times. The event other services receive is
 * then built by this service from its own rows ({@link SpecificationService#published}) and appended to
 * the outbox, so the dataset reaches Formulation and Compliance only through events (architecture §7.4),
 * never by writing into their databases. Event IDs are derived from the version ID ({@code dataset:<id>}),
 * so importing the same file again appends nothing.</p>
 *
 * <p>Enabled by setting {@code spectrace.dataset-import.file}; never on by default.</p>
 */
@Component
@ConditionalOnProperty(prefix = "spectrace.dataset-import", name = "file")
public class DatasetImport implements ApplicationRunner {

    static final String SUBJECT = "dataset-import";
    private static final Logger log = LoggerFactory.getLogger(DatasetImport.class);

    private final SpecificationStore store;
    private final SpecificationService service;
    private final Outbox outbox;
    private final TransactionTemplate transactions;
    private final JsonMapper json;
    private final Path file;

    public DatasetImport(SpecificationStore store, SpecificationService service, Outbox outbox,
                         TransactionTemplate transactions, JsonMapper json,
                         @Value("${spectrace.dataset-import.file}") Path file) {
        this.store = store;
        this.service = service;
        this.outbox = outbox;
        this.transactions = transactions;
        this.json = json;
        this.file = file;
    }

    @Override
    public void run(ApplicationArguments args) {
        log.info("Dataset import appended {} SpecificationPublished.v1 events from {}", importFile(file), file);
    }

    /** Imports every version in the file, each in its own transaction; returns how many events were appended. */
    public int importFile(Path path) {
        List<JsonNode> envelopes = read(path);
        // Release order per material, so previousVersion and the stale-version rule see V1 before V2.
        envelopes.sort(Comparator.comparing((JsonNode e) -> e.path("aggregateId").asString())
                .thenComparingInt(e -> e.path("payload").path("specificationVersion").path("versionNumber").asInt()));
        int appended = 0;
        try (CorrelationId.Scope ignored = CorrelationId.bind("dataset-import-specification")) {
            for (JsonNode envelope : envelopes) {
                if (Boolean.TRUE.equals(transactions.execute(status -> importOne(envelope)))) {
                    appended++;
                }
            }
        }
        return appended;
    }

    private boolean importOne(JsonNode envelope) {
        require(SpecificationPublished.EVENT_TYPE.equals(envelope.path("eventType").asString()),
                "not a " + SpecificationPublished.EVENT_TYPE + " envelope");
        JsonNode payload = envelope.path("payload");
        String organisationId = text(payload, "organisationId");
        String provenanceId = text(payload.path("provenance"), "provenanceId");
        require(store.provenanceSourceType(provenanceId).isPresent(), "unknown provenance " + provenanceId);

        JsonNode supplier = payload.path("supplier");
        String supplierId = text(supplier, "supplierId");
        store.supplier(supplierId).ifPresentOrElse(
                existing -> require(existing.organisationId().equals(organisationId),
                        "supplier " + supplierId + " belongs to another organisation"),
                () -> store.insertSupplier(supplierId, organisationId, text(supplier, "supplierCode"),
                        text(supplier, "supplierName"), provenanceId));

        JsonNode material = payload.path("material");
        String materialId = text(material, "materialId");
        if (store.material(materialId, true).isEmpty()) {
            // Material codes are unique per supplier; the generator reuses one code for every tenant's material.
            String code = text(material, "materialCode");
            if (store.materialCodeExists(supplierId, code)) {
                code = code + "-" + materialId;
            }
            store.insertMaterial(materialId, supplierId, code, text(material, "materialName"), null, provenanceId);
        }
        MaterialRow materialRow = store.material(materialId, true).orElseThrow();
        require(materialRow.supplierId().equals(supplierId), "material " + materialId + " belongs to another supplier");

        JsonNode version = payload.path("specificationVersion");
        String versionId = text(version, "id");
        int versionNumber = version.path("versionNumber").asInt();
        Instant releasedAt = Instant.parse(text(payload, "releasedAt"));
        SpecificationRow existing = store.version(versionId, true).orElse(null);
        if (existing == null) {
            store.insertDraft(versionId, materialId, versionNumber, LocalDate.parse(text(payload, "effectiveDate")),
                    SUBJECT, provenanceId);
            List<String> ingredientIds = payload.path("components").valueStream().map(c -> text(c, "ingredientId")).toList();
            Map<String, SpecificationStore.IngredientRow> ingredients = store.ingredientsById(ingredientIds);
            for (JsonNode component : payload.path("components")) {
                SpecificationStore.IngredientRow ingredient = ingredients.get(text(component, "ingredientId"));
                require(ingredient != null, "unknown ingredient " + text(component, "ingredientId"));
                store.insertComponent(text(component, "specComponentId"), versionId, component.path("sequenceNo").asInt(),
                        ingredient.ingredientId(), text(component, "rawPhrase"), "G3 dataset import",
                        "PLACEHOLDER".equals(ingredient.ingredientKind()) ? "UNMAPPED" : "MATCHED");
            }
            require(store.release(versionId, releasedAt), "version " + versionId + " was not a draft");
            existing = store.version(versionId, false).orElseThrow();
        }
        require(existing.materialId().equals(materialId) && existing.versionNumber() == versionNumber
                && "RELEASED".equals(existing.lifecycleStatus()), "version " + versionId + " differs from the dataset");
        return outbox.appendOnce(Outbox.eventIdFor("dataset:" + versionId), existing.releasedAt(),
                SpecificationPublished.EVENT_TYPE, existing.organisationId(), materialId, versionNumber,
                service.published(existing, materialRow));
    }

    private List<JsonNode> read(Path path) {
        try (var lines = Files.lines(path)) {
            return new java.util.ArrayList<>(lines.filter(line -> !line.isBlank()).map(json::readTree).toList());
        } catch (IOException exception) {
            throw new UncheckedIOException("cannot read dataset " + path, exception);
        }
    }

    private static String text(JsonNode node, String field) {
        String value = node.path(field).asString(null);
        require(value != null && !value.isBlank(), "dataset field " + field + " is missing");
        return value;
    }

    private static void require(boolean condition, String message) {
        if (!condition) {
            throw new IllegalStateException("Dataset import: " + message);
        }
    }
}
